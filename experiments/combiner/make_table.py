#!/usr/bin/env python3
"""Regenerate the combiner routing table and oracle bounds from variant logs.

Reads final wHPWL and GP iterations from each variant's log dir (the same
parse ab_report.py uses) and emits routing_table.md: the 8xN delta table,
single-strategy geomeans, and the three oracle bounds. Run after any variant
rerun lands (e.g. the post-conn-y-fix core 32) so the table never needs
hand-assembly again.

Variant log layout: center uses <design>_run.log, others <design>.log.
Edit VARIANTS to add/remove columns.
"""
import math
import os
import re

GP = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DESIGNS = ["adaptec1", "adaptec2", "adaptec3", "adaptec4",
           "bigblue1", "bigblue2", "bigblue3", "bigblue4"]
# name -> (log dir, filename pattern)
VARIANTS = {
    "center":    ("experiments/obstacle_field/logs/center", "{d}_run.log"),
    "conn-grid": ("experiments/obstacle_field/logs/conn_grid", "{d}.log"),
    "cap-spread": ("experiments/obstacle_field/logs/cap_spread", "{d}.log"),
    "obsfield":  ("experiments/obstacle_field/logs/obsfield", "{d}.log"),
    "obsspread": ("experiments/obstacle_field/logs/obsspread", "{d}.log"),
    "gift":      ("experiments/gift_init/logs", "{d}.log"),
    "shrink001": ("experiments/conn_shrink/logs", "{d}_s001.log"),
}
# completion runs for shrink001 a3/b1/b2 live in the combiner dir
SHRINK_FALLBACK = ("experiments/combiner/logs", "{d}_shrink001.log")
SET4 = ("obsfield", "obsspread", "gift", "shrink001")

FINAL_RE = re.compile(r"iteration\s+(\d+), wHPWL (\S+), time")


def parse(path):
    it = hp = None
    try:
        with open(path) as f:
            for line in f:
                m = FINAL_RE.search(line)
                if m:
                    it, hp = int(m.group(1)), float(m.group(2))
    except FileNotFoundError:
        return None
    return (hp, it) if hp is not None else None


def geomean(deltas):
    return (math.exp(sum(math.log(1 + d / 100) for d in deltas) / len(deltas)) - 1) * 100


table = {}  # design -> variant -> (delta%, iters)
for d in DESIGNS:
    row = {}
    base = parse(os.path.join(GP, VARIANTS["center"][0], VARIANTS["center"][1].format(d=d)))
    if base is None:
        raise SystemExit(f"missing center log for {d}")
    for v, (dirpath, pat) in VARIANTS.items():
        if v == "center":
            continue
        r = parse(os.path.join(GP, dirpath, pat.format(d=d)))
        if r is None and v == "shrink001":
            r = parse(os.path.join(GP, SHRINK_FALLBACK[0], SHRINK_FALLBACK[1].format(d=d)))
        if r is not None:
            row[v] = ((r[0] / base[0] - 1) * 100, r[1])
    table[d] = (row, base[1])

names = [v for v in VARIANTS if v != "center"]
out = ["# Combiner routing table (auto-generated by make_table.py)", ""]
out.append("| design | " + " | ".join(names) + " | center iters |")
out.append("|---" * (len(names) + 2) + "|")
for d in DESIGNS:
    row, cit = table[d]
    best = min((v for v in row), key=lambda v: row[v][0], default=None)
    cells = []
    for v in names:
        if v not in row:
            cells.append("—")
        else:
            s = f"{row[v][0]:+.2f}% ({row[v][1]}it)"
            cells.append(f"**{s}**" if v == best else s)
    out.append(f"| {d} | " + " | ".join(cells) + f" | {cit} |")

out.append("")
for v in names:
    ds = [table[d][0][v][0] for d in DESIGNS if v in table[d][0]]
    tag = "" if len(ds) == len(DESIGNS) else f" (n={len(ds)})"
    out.append(f"- always-{v}: {geomean(ds):+.2f}%{tag}")

full = [min(r[v][0] for v in r) for r, _ in table.values()]
set4 = [min(r[v][0] for v in r if v in SET4) for r, _ in table.values()]
orc = [min(0.0, m) for m in full]
out.append("")
out.append(f"- oracle-always (all variants): {geomean(full):+.2f}%")
out.append(f"- oracle-always (set4 {'/'.join(SET4)}): {geomean(set4):+.2f}%")
out.append(f"- oracle-or-center: {geomean(orc):+.2f}%")

dest = os.path.join(GP, "experiments/combiner/routing_table.md")
open(dest, "w").write("\n".join(out) + "\n")
print("\n".join(out))
print(f"\nwrote {dest}")
